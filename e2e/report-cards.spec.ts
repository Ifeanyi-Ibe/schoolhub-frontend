// Report cards (ADR 0024, slice 4) against the test double: generate the class's cards, download a PDF, see a withheld card refused,
// and publish with the server's counts. The fake keeps its state for the run, so the assertions accept counts from an earlier run.
import AxeBuilder from "@axe-core/playwright";
import type { BrowserContext, Page } from "@playwright/test";
import { fakeJwt } from "./fake-api";
import { test, expect } from "./fixtures";
import { COOKIE, SCHOOL_ORIGIN } from "./origin";

const WCAG = ["wcag2a", "wcag2aa", "wcag21aa", "wcag22aa"];

async function signInAs(context: BrowserContext, label: string) {
  await context.addCookies([
    { name: COOKIE.at, value: fakeJwt(label), url: SCHOOL_ORIGIN },
    { name: COOKIE.rt, value: `rt:${label}:1`, url: SCHOOL_ORIGIN },
  ]);
}

async function expectNoViolations(page: Page) {
  const results = await new AxeBuilder({ page }).withTags(WCAG).analyze();
  expect(results.violations, JSON.stringify(results.violations, null, 2)).toEqual([]);
}

test.describe("report cards for an administrator", () => {
  // The cards are generated by the first journey, and the others read them: the journeys run in order.
  test.describe.configure({ mode: "serial" });

  test.beforeEach(async ({ context }) => {
    await signInAs(context, "admin");
  });

  test("cards are generated, listed with their withheld state, and a withheld card is refused", async ({
    page,
  }) => {
    await page.goto("/report-cards");
    await expect(page.getByRole("heading", { name: "Report cards", exact: true })).toBeVisible();

    await page.getByRole("button", { name: "Generate report cards" }).click();
    await expect(page.getByText(/Generated \d+ cards; \d+ skipped\./)).toBeVisible();

    await expect(page.getByRole("heading", { name: "Cards", exact: true })).toBeVisible();
    await expect(page.getByText("Ada Okafor")).toBeVisible();
    await expect(page.getByText("Withheld: school fees").first()).toBeVisible();

    // A withheld card cannot be downloaded: the screen says so, and no file is saved.
    const withheld = page.locator("li", { hasText: "Bola Musa" });
    await withheld.getByRole("button", { name: "Download PDF" }).click();
    await expect(
      page.getByText("The report card could not be downloaded. Try again."),
    ).toBeVisible();
  });

  test("a card downloads as a PDF", async ({ page }) => {
    await page.goto("/report-cards");
    const ada = page.locator("li", { hasText: "Ada Okafor" });
    await expect(ada).toBeVisible();
    const download = page.waitForEvent("download");
    await ada.getByRole("button", { name: "Download PDF" }).click();
    expect((await download).suggestedFilename()).toBe("report-card.pdf");
  });

  test("publishing shows the server's counts, with withheld cards counted", async ({ page }) => {
    await page.goto("/report-cards");
    await expect(page.getByRole("heading", { name: "Publish", exact: true })).toBeVisible();
    await page.getByRole("button", { name: "Publish results" }).click();
    await page.getByRole("button", { name: "Publish now" }).click();
    await expect(page.getByText(/Published \d+ cards; 1 withheld for school fees\./)).toBeVisible();
  });

  test("the report cards screen is free of axe violations", async ({ page }) => {
    await page.goto("/report-cards");
    await expect(page.getByRole("heading", { name: "Report cards", exact: true })).toBeVisible();
    await expectNoViolations(page);
  });
});

test.describe("report cards for a teacher", () => {
  test("a teacher sees the cards but cannot generate or publish", async ({ page, context }) => {
    await signInAs(context, "teacher");
    await page.goto("/report-cards");
    await expect(page.getByRole("heading", { name: "Report cards", exact: true })).toBeVisible();
    await expect(page.getByRole("button", { name: "Generate report cards" })).toHaveCount(0);
    await expect(page.getByRole("heading", { name: "Publish", exact: true })).toHaveCount(0);
  });
});
