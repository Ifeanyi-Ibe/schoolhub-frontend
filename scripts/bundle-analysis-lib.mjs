// Attributes the bytes of a minified production chunk to the modules that produced them, using the
// chunk's source map. Pure functions, so they can be unit tested. Used by check-bundle-size.mjs when
// BUNDLE_REPORT=1 (the build then emits source maps; see next.config.ts).

const B64 = "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/";
const B64_INDEX = new Map([...B64].map((c, i) => [c, i]));

/** Decodes one base64-VLQ segment into its signed integers. */
export function decodeVlq(segment) {
  const values = [];
  let value = 0;
  let shift = 0;
  for (const ch of segment) {
    const digit = B64_INDEX.get(ch);
    if (digit === undefined) throw new Error(`invalid base64 VLQ character: ${ch}`);
    const continuation = digit & 32;
    value += (digit & 31) << shift;
    if (continuation) {
      shift += 5;
    } else {
      const negative = value & 1;
      const magnitude = value >> 1;
      values.push(negative ? -magnitude : magnitude);
      value = 0;
      shift = 0;
    }
  }
  return values;
}

/**
 * Parses a source map's `mappings` into segments per generated line:
 * [{ col, src }] where src is the index into `sources`, or -1 when the segment has no source.
 */
export function parseMappings(mappings) {
  const lines = [];
  let srcIndex = 0;
  for (const line of mappings.split(";")) {
    const segments = [];
    let genCol = 0;
    for (const seg of line.split(",")) {
      if (seg === "") continue;
      const v = decodeVlq(seg);
      genCol += v[0] ?? 0;
      if (v.length >= 4) {
        srcIndex += v[1] ?? 0;
        // Source line and column deltas (v[2], v[3]) are not needed to attribute bytes.
        segments.push({ col: genCol, src: srcIndex });
      } else {
        segments.push({ col: genCol, src: -1 });
      }
    }
    lines.push(segments);
  }
  return lines;
}

/**
 * Names the owner of a source path: the npm package for node_modules (scoped names kept whole),
 * otherwise the first three directories under src/ (for example "src/features/auth").
 */
export function ownerOf(sourcePath) {
  const nm = sourcePath.lastIndexOf("node_modules/");
  if (nm !== -1) {
    const rest = sourcePath.slice(nm + "node_modules/".length).split("/");
    return rest[0]?.startsWith("@") ? `${rest[0]}/${rest[1]}` : (rest[0] ?? "(unknown)");
  }
  const src = sourcePath.indexOf("/src/");
  if (src !== -1) {
    const parts = sourcePath
      .slice(src + 1)
      .split("/")
      .slice(0, 3);
    return parts.length === 3 && !parts[2].includes(".")
      ? parts.join("/")
      : parts.slice(0, 2).join("/");
  }
  return "(other)";
}

/**
 * Splits a chunk's generated bytes between owners. Each mapped segment owns the text up to the next
 * segment on its line; text not covered by any segment is "(unmapped)". Returns raw bytes per owner.
 */
export function attributeChunk(code, map) {
  const owners = new Map();
  const add = (owner, n) => owners.set(owner, (owners.get(owner) ?? 0) + n);
  const parsed = parseMappings(map.mappings);
  const lines = code.split("\n");
  lines.forEach((text, i) => {
    // Every line but the last is followed by a newline, which is counted as its own owner.
    const newline = i < lines.length - 1 ? 1 : 0;
    const segments = parsed[i] ?? [];
    if (segments.length === 0) {
      add("(unmapped)", Buffer.byteLength(text));
      if (newline) add("(newline)", newline);
      return;
    }
    const first = segments[0].col;
    if (first > 0) add("(unmapped)", Buffer.byteLength(text.slice(0, first)));
    segments.forEach((seg, k) => {
      const end = k + 1 < segments.length ? segments[k + 1].col : text.length;
      const span = text.slice(seg.col, end);
      const owner = seg.src >= 0 ? ownerOf(map.sources[seg.src] ?? "(other)") : "(unmapped)";
      add(owner, Buffer.byteLength(span));
    });
    if (newline) add("(newline)", newline);
  });
  return owners;
}

/** Sorts owners by raw bytes, largest first, with each owner's share of the total. */
export function rankOwners(owners) {
  const total = [...owners.values()].reduce((a, b) => a + b, 0);
  return [...owners.entries()]
    .sort((a, b) => b[1] - a[1])
    .map(([owner, raw]) => ({ owner, raw, share: total === 0 ? 0 : raw / total }));
}
