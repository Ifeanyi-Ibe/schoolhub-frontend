#!/usr/bin/env node
// Generates the typed API client input from docs/openapi/v1.json (the contract).
//
//   node scripts/gen-api.mjs          regenerate outputs and the contract hash
//   node scripts/gen-api.mjs --check  fail if any output or the hash is stale (CI drift check)
//
// Outputs:
//   src/lib/api/schema.d.ts               paths/components types (openapi-typescript)
//   src/lib/api/operations.generated.ts   operation manifest: idempotency, If-Match, permission, x-* extensions
//   docs/openapi/v1.json.sha256           SHA-256 of the contract the outputs were built from

import { createHash } from "node:crypto";
import { readFileSync, writeFileSync, existsSync, mkdirSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import openapiTS, { astToString } from "openapi-typescript";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const specPath = resolve(root, "docs/openapi/v1.json");
const hashPath = resolve(root, "docs/openapi/v1.json.sha256");
const schemaPath = resolve(root, "src/lib/api/schema.d.ts");
const manifestPath = resolve(root, "src/lib/api/operations.generated.ts");
const checkMode = process.argv.includes("--check");

const METHODS = ["get", "put", "post", "delete", "options", "head", "patch", "trace"];
const PERMISSION_LINE = /Requires permission:?\*\*:?\s*([^\n]*)/;
const BACKTICKED = /`([^`]+)`/g;

function operationsFrom(spec) {
  const ops = [];
  for (const [path, item] of Object.entries(spec.paths ?? {})) {
    for (const method of METHODS) {
      const op = item[method];
      if (!op) continue;
      const headerParams = [...(item.parameters ?? []), ...(op.parameters ?? [])]
        .filter((p) => p && p.in === "header")
        .map((p) => p.name);
      const description = `${op.summary ?? ""}\n${op.description ?? ""}`;
      const permLine = PERMISSION_LINE.exec(description)?.[1] ?? "";
      const permissions = [...permLine.matchAll(BACKTICKED)].map((m) => m[1]);
      const anonymous = Array.isArray(op.security) && op.security.length === 0;
      const access = anonymous
        ? "anonymous"
        : permissions.length > 0
          ? "permission"
          : /Requires:\*\*\s*a signed-in person/i.test(description)
            ? "signed-in"
            : "unspecified";
      const extensions = Object.fromEntries(Object.entries(op).filter(([k]) => k.startsWith("x-")));
      ops.push({
        id: `${method.toUpperCase()} ${path}`,
        method: method.toUpperCase(),
        path,
        tag: op.tags?.[0] ?? null,
        idempotent: headerParams.includes("Idempotency-Key"),
        ifMatch: headerParams.includes("If-Match"),
        access,
        permissions,
        extensions,
      });
    }
  }
  return ops.sort((a, b) => (a.id < b.id ? -1 : a.id > b.id ? 1 : 0));
}

function manifestSource(ops) {
  return `// GENERATED by scripts/gen-api.mjs from docs/openapi/v1.json. Do not edit by hand.
// Describes which operations exist and which header policies they declare. The frontend reads
// this (through src/lib/capabilities.ts) instead of guessing from paths.

export interface OperationInfo {
  /** "METHOD /api/v1/path" */
  readonly id: string;
  readonly method: string;
  readonly path: string;
  readonly tag: string | null;
  /** The contract declares an Idempotency-Key header: auto-retry is allowed. */
  readonly idempotent: boolean;
  /** The contract declares an If-Match header: send the row version. */
  readonly ifMatch: boolean;
  readonly access: "anonymous" | "signed-in" | "permission" | "unspecified";
  readonly permissions: readonly string[];
  /** Raw x-* extensions from the contract (machine-readable feature flags, etc.). */
  readonly extensions: Readonly<Record<string, unknown>>;
}

export const OPERATIONS: readonly OperationInfo[] = ${JSON.stringify(ops, null, 2)};
`;
}

async function schemaSource(spec) {
  const ast = await openapiTS(withoutDevTenantHeader(spec), {});
  return `// GENERATED by scripts/gen-api.mjs (openapi-typescript) from docs/openapi/v1.json. Do not edit.\n${astToString(ast)}`;
}

// The contract documents X-Tenant as a Development-only parameter. The BFF always sets the school
// itself (trusted key, backend ADR 0026), so the browser client never sends it. Removed from the
// generated types only; docs/openapi/v1.json stays byte-for-byte as exported.
function withoutDevTenantHeader(spec) {
  const copy = structuredClone(spec);
  const drop = (params) =>
    params ? params.filter((p) => !(p && p.in === "header" && p.name === "X-Tenant")) : params;
  for (const item of Object.values(copy.paths ?? {})) {
    if (item.parameters) item.parameters = drop(item.parameters);
    for (const m of METHODS) if (item[m]?.parameters) item[m].parameters = drop(item[m].parameters);
  }
  return copy;
}

function sha256(text) {
  return createHash("sha256").update(text).digest("hex");
}

async function main() {
  const specText = readFileSync(specPath, "utf8");
  const spec = JSON.parse(specText);
  const outputs = [
    { path: schemaPath, content: await schemaSource(spec) },
    { path: manifestPath, content: manifestSource(operationsFrom(spec)) },
  ];
  const specHash = `${sha256(specText)}  docs/openapi/v1.json\n`;

  if (checkMode) {
    const stale = [];
    for (const out of outputs) {
      if (!existsSync(out.path) || readFileSync(out.path, "utf8") !== out.content)
        stale.push(out.path);
    }
    if (!existsSync(hashPath) || readFileSync(hashPath, "utf8") !== specHash) stale.push(hashPath);
    if (stale.length > 0) {
      console.error("API drift: generated files are stale or the contract changed:");
      for (const f of stale) console.error(`  ${f.replace(root + "/", "")}`);
      console.error("Run `npm run api:gen` and commit the result.");
      process.exit(1);
    }
    console.log(
      `API client up to date (${outputs.length} generated files, contract ${specHash.slice(0, 12)}).`,
    );
    return;
  }

  for (const out of outputs) {
    mkdirSync(dirname(out.path), { recursive: true });
    writeFileSync(out.path, out.content);
  }
  writeFileSync(hashPath, specHash);
  console.log(
    `Generated ${outputs.length} files from docs/openapi/v1.json (${specHash.slice(0, 12)}).`,
  );
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
